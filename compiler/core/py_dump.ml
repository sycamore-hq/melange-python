(* Print Py IR as Python 3.12 source. *)

let quote s =
  let buf = Buffer.create (String.length s + 2) in
  Buffer.add_char buf '"';
  String.iter
    (fun c ->
      match c with
      | '\\' -> Buffer.add_string buf "\\\\"
      | '"' -> Buffer.add_string buf "\\\""
      | '\n' -> Buffer.add_string buf "\\n"
      | '\r' -> Buffer.add_string buf "\\r"
      | '\t' -> Buffer.add_string buf "\\t"
      | c when Char.code c < 32 ->
          Printf.bprintf buf "\\x%02x" (Char.code c)
      | c -> Buffer.add_char buf c)
    s;
  Buffer.add_char buf '"';
  Buffer.contents buf

let rec expr = function
  | Py.Unit -> "None"
  | Py.Bool true -> "True"
  | Py.Bool false -> "False"
  | Py.Int n -> string_of_int n
  | Py.Num lit -> lit
  | Py.Str s -> quote s
  | Py.Name name -> name
  | Py.Call (fn, args) -> call (expr fn) args
  | Py.Runtime (fn, args) -> call fn args

and call fn args =
  fn ^ "(" ^ String.concat ", " (List.map expr args) ^ ")"

let rec uses_runtime name stmts =
  List.exists (stmt_uses name) stmts

and stmt_uses name = function
  | Py.Assign (_, e) | Py.Expr e | Py.Return e -> expr_uses name e
  | Py.Function { body; _ } | Py.While { body; _ } -> uses_runtime name body
  | Py.If (c, t, e) -> expr_uses name c || uses_runtime name t || uses_runtime name e
  | Py.Pass -> false

and expr_uses name = function
  | Py.Runtime (fn, args) -> fn = name || List.exists (expr_uses name) args
  | Py.Call (fn, args) -> expr_uses name fn || List.exists (expr_uses name) args
  | Py.Unit | Py.Bool _ | Py.Int _ | Py.Num _ | Py.Str _ | Py.Name _ -> false

let add_line buf indent line =
  for _ = 1 to indent do
    Buffer.add_string buf "    "
  done;
  Buffer.add_string buf line;
  Buffer.add_char buf '\n'

let rec dump_stmt buf indent = function
  | Py.Assign (name, value) ->
      add_line buf indent (name ^ " = " ^ expr value)
  | Py.Expr e -> add_line buf indent (expr e)
  | Py.Return e -> add_line buf indent ("return " ^ expr e)
  | Py.Pass -> add_line buf indent "pass"
  | Py.Function { name; params; body } ->
      add_line buf indent
        ("def " ^ name ^ "(" ^ String.concat ", " params ^ "):");
      dump_block buf (indent + 1) body
  | Py.If (cond, then_, else_) ->
      add_line buf indent ("if " ^ expr cond ^ ":");
      dump_block buf (indent + 1) then_;
      add_line buf indent "else:";
      dump_block buf (indent + 1) else_
  | Py.While { test; body } ->
      add_line buf indent ("while " ^ expr test ^ ":");
      dump_block buf (indent + 1) body

and dump_block buf indent stmts =
  match stmts with
  | [] -> add_line buf indent "pass"
  | stmts -> List.iter (dump_stmt buf indent) stmts

let render (program : Py.program) =
  let buf = Buffer.create 256 in
  Buffer.add_string buf
    "# Generated by Melange (Python target). Do not edit.\n";
  if uses_runtime "print_endline" program then
    Buffer.add_string buf
      "from melange_runtime.stdio import print_endline\n\n";
  dump_block buf 0 program;
  Buffer.contents buf

let write path program =
  let oc = open_out path in
  Fun.protect
    ~finally:(fun () -> close_out oc)
    (fun () -> output_string oc (render program))
